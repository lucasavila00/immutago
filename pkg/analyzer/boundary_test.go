// boundaryPass type-checks a complete package without adding an im import.
func boundaryPass(t *testing.T, importer types.Importer, source string) *analysis.Pass {
	t.Helper()
	positions := token.NewFileSet()
	file, err := parser.ParseFile(positions, "boundary.go", source, parser.ParseComments)
	if err != nil {
		t.Fatal(err)
	}
	info := &types.Info{Types: make(map[ast.Expr]types.TypeAndValue), Defs: make(map[*ast.Ident]types.Object),
		Uses: make(map[*ast.Ident]types.Object), Selections: make(map[*ast.SelectorExpr]*types.Selection),
		Scopes: make(map[ast.Node]*types.Scope), Instances: make(map[*ast.Ident]types.Instance)}
	config := types.Config{Importer: importer}
	pkg, err := config.Check("boundary", positions, []*ast.File{file}, info)
	if err != nil {
		t.Fatal(err)
	}
	return &analysis.Pass{Analyzer: Analyzer, Pkg: pkg, Fset: positions, Files: []*ast.File{file}, TypesInfo: info}
}

// TestOrdinaryPackageBoundary permits ordinary unsafe, reflection, bodyless, and cgo-header source.
func TestOrdinaryPackageBoundary(t *testing.T) {
	library := sourcePass(t, "var _ im.Shared").Pkg.Imports()[0]
	cases := []string{
		`package ordinary; import "unsafe"; var _ unsafe.Pointer`,
		`package ordinary; import "reflect"; var Value = reflect.ValueOf(1)`,
		`package ordinary; func read() int`,
		"// Code generated by cmd/cgo; DO NOT EDIT.\npackage ordinary\nimport _ \"unsafe\"",
	}
	for _, source := range cases {
		pass := boundaryPass(t, testImporter{library}, source)
		pass.Report = func(d analysis.Diagnostic) { t.Fatalf("ordinary package rejected: %s", d.Message) }
		pass.ExportPackageFact = func(analysis.Fact) { t.Fatal("ordinary package exported a failed proof") }
		if _, err := run(pass); err != nil {
			t.Fatal(err)
		}
	}
}

// TestPrunedProofBoundary keeps aliases, inferred callbacks, and Owner contracts checked after import pruning.
func TestPrunedProofBoundary(t *testing.T) {
	api := sourcePass(t, `type Value struct { im.Shared; X int }
 type Model struct { im.Scoped; X int }
 type Loader struct { Current im.Owner[Model] }
 var Current im.Owner[Model]
 func Make() *Value { return &Value{} }
 func Publish(*Loader) {}`).Pkg
	api.SetImports(nil)
	importer := dependencyImporter{"sample": api, "unsafe": types.Unsafe}
	cases := []struct{ name, declarations string }{
		{"alias", `type Alias = api.Value; var value Alias`},
		{"defined", `type Copy api.Value; var value Copy`},
		{"inferred callback", `var callback = api.Make`},
		{"Owner callback", `var callback = api.Publish`},
		{"Owner slot", `var current = api.Current`},
		{"Owner reference", `var holder *api.Loader`},
		{"Owner signature", `type Callback func(*api.Loader)`},
		{"generic constraint", `func read[T interface{*api.Value}](){}`},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			pass := boundaryPass(t, importer,
				`package boundary; import ("unsafe"; api "sample"); var _ unsafe.Pointer; `+tc.declarations)
			if usesImmutable(pass.Pkg) {
				t.Fatal("fixture did not prune the im import graph")
			}
			var reports []string
			pass.Report = func(d analysis.Diagnostic) { reports = append(reports, d.Message) }
			exported := false
			pass.ExportPackageFact = func(f analysis.Fact) { exported = f.(*invalidPackage).Relevant }
			if _, err := run(pass); err != nil {
				t.Fatal(err)
			}
			if !exported || !strings.Contains(strings.Join(reports, "\n"), "unsupported unsafe import") {
				t.Fatalf("pruned package escaped checking: fact=%t, reports=%v", exported, reports)
			}
			pass.TypesInfo.Types = nil
			if !protectedPackage(pass) {
				t.Fatal("object types lost proof relevance")
			}
		})
	}
}
