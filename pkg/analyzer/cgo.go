package analyzer

import (
	"go/ast"
	"go/token"
	"strconv"

	"golang.org/x/tools/go/analysis"
)

const cgoDiagnostic = "cgo is not supported; immutability cannot be proved\n  fix: replace cgo with checked Go code"

// rejectCgo rejects a checked package before checking compiler-generated wrappers.
// The header is a rejection trigger, never an exemption from the proof.
func rejectCgo(pass *analysis.Pass, imports map[string]invalidPackage) bool {
	position := cgoPosition(pass)
	if !position.IsValid() {
		return false
	}
	diagnostic := analysis.Diagnostic{Pos: position, Message: cgoDiagnostic}
	pass.Report(diagnostic)
	if pass.ExportPackageFact != nil {
		pass.ExportPackageFact(packageFailureFact(pass.Pkg.Path(), true, imports,
			[]proofFailure{localFailure(pass, diagnostic)}))
	}
	return true
}

// cgoPosition prefers an original source location from cgo's line directives.
// Both analysis drivers lose the original import C, but retain its package line.
func cgoPosition(pass *analysis.Pass) token.Pos {
	var selected token.Pos
	selectedSource := false
	for _, file := range pass.Files {
		generated, imported := cgoFile(file)
		if !generated && !imported {
			continue
		}
		position := pass.Fset.PositionFor(file.Package, true)
		physical := pass.Fset.PositionFor(file.Package, false)
		source := imported || position.Filename != physical.Filename
		if !selected.IsValid() || source && !selectedSource ||
			source == selectedSource && position.String() < pass.Fset.Position(selected).String() {
			selected, selectedSource = file.Package, source
		}
	}
	return selected
}

// cgoFile recognizes the exact compiler header or an original import of C.
func cgoFile(file *ast.File) (generated, imported bool) {
	for _, group := range file.Comments {
		if group.Pos() > file.Package {
			break
		}
		for _, comment := range group.List {
			if comment.Text == "// Code generated by cmd/cgo; DO NOT EDIT." {
				generated = true
			}
		}
	}
	for _, spec := range file.Imports {
		path, err := strconv.Unquote(spec.Path.Value)
		if err == nil && path == "C" {
			imported = true
		}
	}
	return generated, imported
}
