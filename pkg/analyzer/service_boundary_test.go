// TestPrunedServiceBoundary checks service contracts without a direct im or supervise import.
func TestPrunedServiceBoundary(t *testing.T) {
	api := sourcePass(t, `import("context"; "github.com/lucasavila00/immutago/pkg/supervise")
var _ im.Frozen
type Counter struct {supervise.Service[int]}
func (*Counter) Run(context.Context) {}
func (*Counter) Count() int {return 1}
type Handle = supervise.Ref[Counter]
func Get() Handle {var p Handle;return p}
type Scalar[T interface{~int | Handle}] = int
type Contract interface { Get() Handle }
type Phantom[T any] struct{}
func Make() Phantom[Handle] {return Phantom[Handle]{}}`).Pkg
	api.SetImports(nil)
	for _, declaration := range []string{
		`var ref = api.Get()`,
		`var callback = api.Get`,
		`var ref api.Handle`,
		`var value api.Scalar[int]`,
		`var service api.Contract`,
		`var value = api.Make()`,
	} {
		t.Run(declaration, func(t *testing.T) {
			pass := boundaryPass(t, dependencyImporter{"sample": api},
				`package consumer;import api "sample";func missingBody();`+declaration)
			if importsCheckedLibrary(pass.Pkg, true) {
				t.Fatal("consumer has a direct library import")
			}
			var reports []string
			pass.Report = func(d analysis.Diagnostic) { reports = append(reports, d.Message) }
			if _, err := run(pass); err != nil {
				t.Fatal(err)
			}
			if !protectedPackage(pass) {
				t.Fatal("service contract did not activate checking")
			}
			if len(reports) != 0 {
				t.Fatalf("ordinary function rejected: %v", reports)
			}
		})
	}
}

// TestServiceOnlyPackage keeps ordinary code outside the im source checks.
func TestServiceOnlyPackage(t *testing.T) {
	api := sourcePass(t, `import "github.com/lucasavila00/immutago/pkg/supervise"
 var _ im.Frozen; var _ supervise.NoArgs`).Pkg
	imports := testImporter{standard: importer.Default()}
	for _, pkg := range api.Imports() {
		if pkg.Path() == checker.RuntimePath {
			imports.runtime = pkg
		}
	}
	for _, source := range []string{
		`package service; import "github.com/lucasavila00/immutago/pkg/supervise"
   type Counter struct{supervise.Service[supervise.NoArgs]}; func(c *Counter) Count() int`,
		"// Code generated by cmd/cgo; DO NOT EDIT.\npackage service\n" +
			`import "github.com/lucasavila00/immutago/pkg/supervise"; var _ supervise.NoArgs`,
	} {
		pass := boundaryPass(t, imports, source)
		if referencesLibrary(pass, false) {
			t.Fatal("service-only source selected im checks")
		}
		pass.Report = func(d analysis.Diagnostic) { t.Fatalf("ordinary service code rejected: %s", d.Message) }
		if _, err := run(pass); err != nil {
			t.Fatal(err)
		}
	}
}
