// TestGenerationConfigurations checks one canonical output per selected schema through both drivers.
func TestGenerationConfigurations(t *testing.T) {
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	tools := t.TempDir()
	checker := filepath.Join(tools, "immutago")
	generator := filepath.Join(tools, "immutago-gen")
	if runtime.GOOS == "windows" {
		checker += ".exe"
		generator += ".exe"
	}
	runCommand(t, root, true, "go", "build", "-o", checker, "./cmd/immutago")
	runCommand(t, root, true, "go", "build", "-o", generator, "./cmd/immutago-gen")
	for _, name := range []string{"stable", "declaration", "alias", "array", "interface", "platform"} {
		t.Run(name, func(t *testing.T) { checkGenerationChange(t, root, checker, generator, name) })
	}
	t.Run("onlytag", func(t *testing.T) {
		dir := filepath.Join(consumerModule(t, root, "generation_configurations"), "onlytag")
		config := []string{"GOFLAGS=-tags=integration"}
		runGenerationConfig(t, dir, config, true, generator)
		checkGenerationConfig(t, root, dir, checker, "onlytag", config)
		before := readGenerationOutput(t, dir)
		runCommand(t, dir, true, "go", "generate", ".")
		if !bytes.Equal(before, readGenerationOutput(t, dir)) {
			t.Fatal("go generate selected a directive excluded by the build tag")
		}
		runGenerationConfig(t, dir, nil, true, generator)
		want := "// Code generated by immutago-gen. DO NOT EDIT.\n\npackage onlytag\n"
		if string(readGenerationOutput(t, dir)) != want {
			t.Fatal("direct generation did not remove declarations excluded by the build tag")
		}
		checkGenerationConfig(t, root, dir, checker, "onlytag", nil)
	})
	t.Run("imported", func(t *testing.T) {
		dir := consumerModule(t, root, "generation_configurations")
		for _, config := range [][]string{nil, {"GOFLAGS=-tags=integration"}} {
			runGenerationConfig(t, filepath.Join(dir, "alias"), config, true, generator)
			runGenerationConfig(t, filepath.Join(dir, "imported"), config, true, generator)
			checkGenerationConfig(t, root, filepath.Join(dir, "imported"), checker, "imported", config)
		}
	})
}

// checkGenerationChange regenerates each selected schema and restores the original output.
func checkGenerationChange(t *testing.T, root, checker, generator, name string) {
	t.Helper()
	dir := filepath.Join(consumerModule(t, root, "generation_configurations"), name)
	var first []string
	second := []string{"GOFLAGS=-tags=integration"}
	if name == "platform" {
		first = []string{"GOOS=linux", "GOARCH=amd64"}
		second = []string{"GOOS=windows", "GOARCH=amd64"}
	}
	runGenerationConfig(t, dir, first, true, generator)
	before := readGenerationOutput(t, dir)
	checkGenerationConfig(t, root, dir, checker, name, first)
	if name == "array" {
		for _, command := range [][]string{{checker, "."}, {"go", "vet", "-vettool=" + checker, "."}} {
			output := runGenerationConfig(t, dir, second, false, command[0], command[1:]...)
			checkSnapshot(t, filepath.Join(root, "tests/testdata/generation_configurations/array/output.txt"),
				normalizeOutput(output))
		}
	}
	runGenerationConfig(t, dir, second, true, generator)
	after := readGenerationOutput(t, dir)
	if bytes.Equal(before, after) != (name == "stable") {
		t.Fatalf("generated output changed = %t; want %t", !bytes.Equal(before, after), name != "stable")
	}
	checkGenerationConfig(t, root, dir, checker, name, second)
	runGenerationConfig(t, dir, first, true, generator)
	if !bytes.Equal(before, readGenerationOutput(t, dir)) {
		t.Fatal("generation did not restore the first configuration")
	}
	checkGenerationConfig(t, root, dir, checker, name, first)
}

// checkGenerationConfig requires the selected schema to pass the CLI and vet.
func checkGenerationConfig(t *testing.T, root, dir, checker, fixture string, config []string) {
	t.Helper()
	for _, command := range [][]string{{checker, "."}, {"go", "vet", "-vettool=" + checker, "."}} {
		output := runGenerationConfig(t, dir, config, true, command[0], command[1:]...)
		if fixture == "array" {
			if output != "" {
				t.Fatalf("valid configuration has diagnostics: %s", output)
			}
		} else {
			checkSnapshot(t, filepath.Join(root, "tests/testdata/generation_configurations", fixture, "output.txt"),
				normalizeOutput(output))
		}
	}
}

// runGenerationConfig runs host-built tools with the selected target configuration.
func runGenerationConfig(t *testing.T, dir string, config []string, success bool, name string, args ...string) string {
	t.Helper()
	command := exec.Command(name, args...)
	command.Dir = dir
	command.Env = append(append(os.Environ(), "GOWORK=off", "GOFLAGS="), config...)
	output, err := command.CombinedOutput()
	if (err == nil) != success {
		t.Fatalf("%s with %v: %v\n%s", command, config, err, output)
	}
	return string(output)
}

// readGenerationOutput reads the one canonical file for the current configuration.
func readGenerationOutput(t *testing.T, dir string) []byte {
	t.Helper()
	output, err := os.ReadFile(filepath.Join(dir, projectiongen.Filename))
	if err != nil {
		t.Fatal(err)
	}
	return output
}
